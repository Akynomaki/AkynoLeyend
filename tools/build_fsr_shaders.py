"""Rebuild generic AMD FSR filters from GLSL; no game bytecode is involved."""
import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def build(compiler, validator, output):
    output.mkdir(parents=True, exist_ok=True)
    folder = ROOT / "gpu/vk/shaders"
    with tempfile.TemporaryDirectory(prefix="fsr-shaders-") as temp:
        for name in ("fsr_easu", "fsr_rcas"):
            binary = Path(temp) / (name + ".spv")
            subprocess.run([str(compiler), "-V", "--target-env", "vulkan1.3", "-Os", "-I" + str(folder),
                            str(folder / (name + ".comp")), "-o", str(binary)], check=True)
            subprocess.run([str(validator), "--target-env", "vulkan1.3", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            text = "// Generic shader generated by tools/build_fsr_shaders.py from AMD GPUOpen headers.\n#pragma once\n#include <cstdint>\n"
            text += "inline constexpr uint32_t " + name.upper() + "_COMP_SPV[] = {\n"
            text += "".join("    " + ",".join("0x%08x" % w for w in words[i:i + 8]) + ",\n" for i in range(0, len(words), 8))
            text += "};\n"
            (output / (name + "_comp_spv.h")).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", type=Path, required=True)
    parser.add_argument("--validator", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "gpu/vk/shaders")
    args = parser.parse_args()
    build(args.compiler.resolve(), args.validator.resolve(), args.output.resolve())
